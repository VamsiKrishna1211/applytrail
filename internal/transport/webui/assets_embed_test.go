//go:build webui

package webui

import (
	"net/http"
	"net/http/httptest"
	"strings"
	"testing"

	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"
)

// Under the webui tag the bundle is real, so this checks the thing that
// actually ships rather than a fixture: that the embed picked the files up,
// that the document names hashed assets, and that those assets are reachable.
func TestEmbeddedBundleServes(t *testing.T) {
	require.True(t, Available(), "no bundle embedded; run `make web` before building with -tags webui")

	handler := Handler()
	require.NotNil(t, handler)

	recorder := httptest.NewRecorder()
	handler.ServeHTTP(recorder, httptest.NewRequest(http.MethodGet, "/pipeline", nil))

	require.Equal(t, http.StatusOK, recorder.Code)
	document := recorder.Body.String()
	assert.Contains(t, document, "<!doctype html>")
	assert.Contains(t, document, "/assets/", "the document should reference the hashed bundle")

	for _, path := range referencedAssets(document) {
		asset := httptest.NewRecorder()
		handler.ServeHTTP(asset, httptest.NewRequest(http.MethodGet, path, nil))
		assert.Equalf(t, http.StatusOK, asset.Code, "%s is referenced but not embedded", path)
	}
}

// referencedAssets pulls every /assets/... path out of the document. Crude on
// purpose: the document is generated by Vite and only ever quotes these in
// src and href attributes.
func referencedAssets(document string) []string {
	var found []string
	for _, part := range strings.Split(document, `"`) {
		if strings.HasPrefix(part, "/assets/") {
			found = append(found, part)
		}
	}
	return found
}
